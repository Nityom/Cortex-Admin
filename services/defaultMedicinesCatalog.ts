// Fast lookup map by uppercase name or base name
export const MASTER_MEDICINE_MAP = new Map<string, DefaultMedicineItem>();

for (const item of MASTER_MEDICINE_CATALOG) {
  MASTER_MEDICINE_MAP.set(item.name.toUpperCase().trim(), item);
}

export function findMasterMedicine(query: string): DefaultMedicineItem | undefined {
  if (!query) return undefined;
  const clean = query.trim().toUpperCase();
  if (MASTER_MEDICINE_MAP.has(clean)) {
    return MASTER_MEDICINE_MAP.get(clean);
  }
  for (const [key, val] of MASTER_MEDICINE_MAP.entries()) {
    if (clean === key || clean.startsWith(key) || key.startsWith(clean)) {
      return val;
    }
  }
  return undefined;
}
